// Медицинский словарь ../public/models/med.txt: словоформы из медицинских законов (corpus/) и статей Википедии
// (corpus-wiki/) по убыванию частоты. На сайте эти слова получают «частый» ранг — термины вроде «анамнез»
// не проигрывают обычным словам при исправлении. Плюс короткие медицинские сокращения.
// Запуск: node build-med.cjs
const fs = require("fs");
const norm = (w) => w.toLowerCase().replace(/ё/g, "е");

// Общий словарь (тот же, что грузит сайт)
const known = new Set(fs.readFileSync("../public/models/words.txt", "utf8").split("\n").filter(Boolean).map(norm));
let prev = "";
for (const line of fs.readFileSync("../public/models/forms.txt", "utf8").split("\n")) {
  if (!line) continue;
  prev = prev.slice(0, line.charCodeAt(0) - 48) + line.slice(1);
  known.add(prev);
}

const MED_LAWS = /323_ФЗ|3185_1|73_ФЗ|326_ФЗ|61_ФЗ|125_ФЗ/;
const files = [
  ...fs.readdirSync("corpus").filter((f) => MED_LAWS.test(f)).map((f) => "corpus/" + f),
  ...(fs.existsSync("corpus-wiki") ? fs.readdirSync("corpus-wiki").map((f) => "corpus-wiki/" + f) : []),
];
const freq = new Map(), lower = new Map();
for (const f of files) {
  const text = fs.readFileSync(f, "utf8");
  for (const m of text.matchAll(/[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*/g)) {
    const w = m[0];
    if (w.length < 3) continue;
    const k = norm(w);
    freq.set(k, (freq.get(k) || 0) + 1);
    if (w === w.toLowerCase()) lower.set(k, (lower.get(k) || 0) + 1);
  }
}

